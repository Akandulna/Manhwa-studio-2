import { Bot } from 'lucide-react'
import type { NarrationLanguage } from '@/lib/narrationLanguage'
import { getTimelineModel } from './timelineHandoff'

export function TimelineModelBadge({ chapterId, language }: { chapterId: string; language: NarrationLanguage }) {
  const model = getTimelineModel(chapterId, language)
  return (
    <span title={model ? `Timeline generated by ${model}` : 'The AI model was not recorded for this timeline.'}
      className="inline-flex items-center gap-1 rounded-full border border-border bg-background/90 px-2 py-0.5 text-[11px] text-muted-foreground max-w-[16rem]">
      <Bot className="h-3 w-3 flex-shrink-0" />
      <span className="truncate">{model || 'AI not recorded'}</span>
    </span>
  )
}
