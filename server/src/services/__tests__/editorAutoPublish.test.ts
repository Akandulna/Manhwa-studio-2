import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const { packages, timelines, resets } = vi.hoisted(() => ({ packages: vi.fn(), timelines: vi.fn(), resets: vi.fn() }))
vi.mock('../phoneEditor.js', () => ({ publishReadyEditorPackages: packages, publishSavedEditorTimelines: timelines, publishEditorTimelineResets: resets }))
beforeEach(() => {
  vi.resetModules()
  vi.useFakeTimers()
  packages.mockReset().mockResolvedValue({ sent: [], failed: [] })
  resets.mockReset().mockResolvedValue({ sent: [], failed: [] })
  timelines.mockReset().mockResolvedValue({ sent: [], failed: [] })
})
afterEach(() => { vi.clearAllTimers(); vi.useRealTimers() })
describe('automatic timeline publication', () => {
  it('batches saves and publishes both packages and edits', async () => {
    const { queueEditorPublish } = await import('../editorAutoPublish.js')
    queueEditorPublish('c1'); queueEditorPublish('c2'); queueEditorPublish('c1')
    await vi.advanceTimersByTimeAsync(5000)
    expect(resets).toHaveBeenCalledWith(['c1', 'c2'])
    expect(resets.mock.invocationCallOrder[0]).toBeLessThan(packages.mock.invocationCallOrder[0])
    expect(packages).toHaveBeenCalledWith(['c1', 'c2'])
    expect(timelines).toHaveBeenCalledWith(['c1', 'c2'])
  })
  it('retries failed timeline uploads without another user save', async () => {
    timelines.mockResolvedValueOnce({ sent: [], failed: [{ chapterId: 'c1', language: 'en', error: 'offline' }] })
    const { queueEditorPublish } = await import('../editorAutoPublish.js')
    queueEditorPublish('c1')
    await vi.advanceTimersByTimeAsync(5000)
    expect(timelines).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(30000)
    expect(timelines).toHaveBeenCalledTimes(2)
    expect(timelines).toHaveBeenLastCalledWith(['c1'])
  })
  it('retries reviewed package delivery after a failed device sync request', async () => {
    packages.mockResolvedValueOnce({ sent: [], failed: [{ chapterId: 'c1', language: 'hi', error: 'Could not request device sync' }] })
    const { queueEditorPublish } = await import('../editorAutoPublish.js')
    queueEditorPublish('c1')
    await vi.advanceTimersByTimeAsync(5000)
    expect(packages).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(30000)
    expect(packages).toHaveBeenCalledTimes(2)
    expect(packages).toHaveBeenLastCalledWith(['c1'])
  })
  it('waits for a revised save after a validation conflict instead of retrying forever', async () => {
    timelines.mockResolvedValueOnce({ sent: [], failed: [{ chapterId: 'c1', language: 'en', error: 'inputs changed', retryable: false }] })
    const { queueEditorPublish } = await import('../editorAutoPublish.js')
    queueEditorPublish('c1')
    await vi.advanceTimersByTimeAsync(65000)
    expect(timelines).toHaveBeenCalledTimes(1)
    queueEditorPublish('c1')
    await vi.advanceTimersByTimeAsync(5000)
    expect(timelines).toHaveBeenCalledTimes(2)
  })
  it('recovers durable unsent edits at startup', async () => {
    const { publishEditorPackagesAtStartup } = await import('../editorAutoPublish.js')
    publishEditorPackagesAtStartup()
    await vi.advanceTimersByTimeAsync(35000)
    expect(timelines).toHaveBeenCalledWith(null)
  })
  it('recovers transport discovery failures and keeps later saves', async () => {
    timelines.mockRejectedValueOnce(new Error('R2 unavailable'))
    const { queueEditorPublish } = await import('../editorAutoPublish.js')
    queueEditorPublish('c1')
    await vi.advanceTimersByTimeAsync(5000)
    queueEditorPublish('c2')
    await vi.advanceTimersByTimeAsync(5000)
    expect(timelines).toHaveBeenLastCalledWith(['c1', 'c2'])
  })
})
